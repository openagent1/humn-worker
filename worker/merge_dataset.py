def _extract_text(row: dict) -> str | None:
    """Pull usable text from any known schema. Returns None if none found."""
    for key in ("text", "selftext", "tweet", "content", "body", "prompt"):
        v = row.get(key)
        if isinstance(v, str) and v.strip():
            return v
    # Aya-style: inputs + targets
    parts = []
    for key in ("inputs", "targets", "completion", "response"):
        v = row.get(key)
        if isinstance(v, dict):
            v = v.get("text") or json.dumps(v, ensure_ascii=False)
        if isinstance(v, str) and v.strip():
            parts.append(v)
    if parts:
        return "\n".join(parts)
    return None


def main() -> int:

    ap = argparse.ArgumentParser()
    ap.add_argument("--jobs-dir", required=True)
    ap.add_argument("--workdir", required=True)
    ap.add_argument("--out-repo", required=True,
                    help="e.g. yourname/humn-social-register-v0.2, or 'auto'")
    ap.add_argument("--dataset-version", default="v0.2",
                    help="used for auto repo naming + dataset card title")
    ap.add_argument("--token", default=None, help="HF write token (or env HUMN_OUT_TOKEN)")
    ap.add_argument("--max-rows", type=int, default=None)
    ap.add_argument("--download", action="store_true",
                    help="download finished chunks from the HF checkpoint repo")
    ap.add_argument("--upload", action="store_true", help="actually upload (default: dev, local only)")
    ap.add_argument("--exclude-sources", default="",
                    help="comma-separated source repos to EXCLUDE (e.g. lmsys/lmsys-chat-1m for public releases)")
    ap.add_argument("--only-jobs", default="",
                    help="comma-separated job_ids to process (sharded merge legs); empty = all specs")
    ap.add_argument("--out-prefix", default="",
                    help="prefix for all upload paths, e.g. a leg name (work-repo staging); skips README upload")
    ap.add_argument("--save-stats", default="",
                    help="write build counters JSON here (also uploaded next to outputs when uploading)")
    ap.add_argument("--split-by-lang", action=argparse.BooleanOptionalAction, default=True,
                    help="write per-language pretrain_<lang>/ dirs instead of one pretrain/ dir")
    ap.add_argument("--include-raw", action="store_true", default=False,
                    help="also publish raw/<job>/ provenance dumps (default: slim release without them)")
    ap.add_argument("--flag-content", action=argparse.BooleanOptionalAction, default=True,
                    help="lexicon-based quality flags (political/toxic/spam/low_info); labels, never deletes")
    ap.add_argument("--curated", default=None,
                    help="path to curated JSONL (prompt/response/dialect/register per TEMPLATE) merged as source humn_curated")
    args = ap.parse_args()

    token = args.token or __import__("os").environ.get("HUMN_OUT_TOKEN") or __import__("os").environ.get("HF_TOKEN_RW")
    if args.out_repo == "auto":
        if not token:
            log("[error] --out-repo auto needs a token to resolve your username", file=sys.stderr)
            return 1
        from worker_core import hf_whoami
        user = hf_whoami(token)
        ver = args.dataset_version.lstrip("v")
        args.out_repo = f"{user}/humn-social-register-v{ver}"
        log(f"[auto] output repo: {args.out_repo}")
    elif args.out_repo == "auto-work":
        if not token:
            log("[error] --out-repo auto-work needs a token to resolve your username", file=sys.stderr)
            return 1
        from worker_core import hf_whoami
        user = hf_whoami(token)
        args.out_repo = f"{user}/humn-v1-work"
        log(f"[auto] work repo: {args.out_repo}")
    workdir = Path(args.workdir)
    workdir.mkdir(parents=True, exist_ok=True)

    jobs_dir = Path(args.jobs_dir)
    excluded = {s.strip() for s in args.exclude_sources.split(",") if s.strip()}
    if excluded:
        log(f"[exclude] dropping sources from public release: {sorted(excluded)}")
    only = {j.strip() for j in args.only_jobs.split(",") if j.strip()}
    if only:
        log(f"[only-jobs] processing {len(only)} job(s): {sorted(only)}")
    UP_PREFIX = args.out_prefix.strip("/")  # upload namespace for legs; never reuse this name below
    composition: list[str] = []
    seen_texts: set[str] = set()
    n_dup = 0
    # v1 layout: per-language pretrain_<lang>/ + per-language sft_chat_<lang>/,
    # each a separate HF config with ONE uniform canonical schema.
    # ShardWriter keeps every file <= ~400MB (viewer-friendly).
    final_dir = workdir / "final"
    final_dir.mkdir(parents=True, exist_ok=True)
    pretrain_writers: dict[str, ShardWriter] = {}
    chat_writers: dict[str, ShardWriter] = {}
    split_counts: Counter = Counter()
    import hashlib

    def _h(s: str) -> bytes:
        return hashlib.sha1(s.encode("utf-8", "replace")).digest()

    conversations: dict[str, list] = {}   # conversation_id -> turns
    conv_source: dict[str, str] = {}
    lang_counter: Counter = Counter()     # language mix stats
    used_sources: set[str] = set()
    # v1 quality stats
    seen_norm: set[str] = set()
    n_norm_dup = 0
    flag_counter: Counter = Counter()
    _char_sum = 0
    _char_n = 0
    _emoji_rows = 0
    _url_rows = 0
    _len_reservoir: list[int] = []

    def bump_stats(t: str) -> None:
        nonlocal _char_sum, _char_n, _emoji_rows, _url_rows
        _char_sum += len(t)
        _char_n += 1
        if has_emoji(t):
            _emoji_rows += 1
        if "http" in t or "t.me/" in t:
            _url_rows += 1
        if len(_len_reservoir) < 20000:
            _len_reservoir.append(len(t))

    def pretrain_writer(split: str) -> ShardWriter:
        if split not in pretrain_writers:
            pretrain_writers[split] = ShardWriter(final_dir / f"pretrain_{split}")
        return pretrain_writers[split]

    def chat_writer(split: str) -> ShardWriter:
        if split not in chat_writers:
            chat_writers[split] = ShardWriter(final_dir / f"sft_chat_{split}")
        return chat_writers[split]

    for spec_file in sorted(jobs_dir.glob("*.yaml")):
        with open(spec_file, encoding="utf-8") as f:
            spec = yaml.safe_load(f) or {}
        if not spec:
            continue
        job_id = spec.get("job_id", spec_file.stem)
        if only and job_id not in only:
            continue
        src_repo = spec["data_source"].get("repo") or spec["data_source"].get("url", "unknown")
        if src_repo in excluded:
            log(f"[excluded] {job_id} ({src_repo}) — purged from this release")
            continue
        manifest_p = workdir / job_id / "manifest.json"

        if not manifest_p.exists() and args.download:
            # pull manifest + done chunks from the (resolved) checkpoint repo
            if not token:
                log(f"[skip] {job_id}: --download needs a token", file=sys.stderr)
                continue
            from worker_core import resolve_repo
            ckpt_repo = resolve_repo(spec["checkpoint"]["repo"], token)
            try:
                from huggingface_hub import hf_hub_download  # type: ignore
                mpath = hf_hub_download(repo_id=ckpt_repo, filename="manifest.json",
                                        repo_type="dataset", token=token)
                manifest = json.loads(Path(mpath).read_text(encoding="utf-8"))
                manifest_p.parent.mkdir(parents=True, exist_ok=True)
                manifest_p.write_text(json.dumps(manifest, ensure_ascii=False), encoding="utf-8")
                for ci, c in enumerate(manifest["chunks"]):
                    if c["status"] == "done":
                        log(f"  [download] {job_id}/{c['chunk_id']}.jsonl ...")
                        cp = hf_hub_download(repo_id=ckpt_repo,
                                             filename=f"{job_id}/{c['chunk_id']}.jsonl",
                                             repo_type="dataset", token=token)
                        dst = workdir / job_id / f"{c['chunk_id']}.jsonl"
                        dst.parent.mkdir(parents=True, exist_ok=True)
                        if not dst.exists():
                            import shutil
                            shutil.copy(cp, dst)
                log(f"[download] {job_id}: chunks fetched from {ckpt_repo}")
            except Exception as e:  # noqa: BLE001
                log(f"[skip] {job_id}: no remote checkpoint ({type(e).__name__}: {str(e)[:150]})")
                continue

        if not manifest_p.exists():
            log(f"[skip] {job_id}: no manifest (job not run)")
            continue
        manifest = json.loads(manifest_p.read_text(encoding="utf-8"))
        done = [c for c in manifest["chunks"] if c["status"] == "done"]
        used_sources.add(src_repo)
        spec_lang = (spec.get("metadata") or {}).get("lang")
        log(f"[merge] {job_id}: {len(done)} chunks from {src_repo}"
              + (f" (spec lang: {spec_lang})" if spec_lang else ""))
        raw_out = None
        raw_n = 0
        if args.include_raw:
            raw_job_dir = final_dir / "raw" / job_id
            raw_job_dir.mkdir(parents=True, exist_ok=True)
            raw_out = open(raw_job_dir / "train.jsonl", "w", encoding="utf-8")
        n = 0
        for c in done:
            chunk_p = workdir / job_id / f"{c['chunk_id']}.jsonl"
            if not chunk_p.exists():
                log(f"  [warn] chunk file missing: {chunk_p.name}")
                continue
            log(f"  [merge] {job_id}/{c['chunk_id']}.jsonl ...")
            with open(chunk_p, encoding="utf-8") as fh:
                for li, line in enumerate(fh):
                    if li and li % 500000 == 0:
                        log(f"    ... {li:,} lines into {c['chunk_id']}.jsonl")
                    try:
                        rec = json.loads(line)
                    except json.JSONDecodeError:
                        n_dup += 1
                        continue
                    rec["source"] = src_repo
                    # ---- canonical routing ----
                    row = rec.get("row", {})
                    if not isinstance(row, dict):
                        row = {"value": row}
                    role = ROLE_MAP.get(str(row.get("role", "")).lower())
                    content = row.get("content")
                    # strict chat rule: real conversation threading only
                    # (parent_conversation_id + ordered turns). OASST2-style
                    # parent_id rows go to pretrain as texts instead.
                    conv_id = row.get("parent_conversation_id")
                    if role in ("user", "assistant") and isinstance(content, str) and conv_id:
                        key = (row.get("_turn_idx", 0), role, content)
                        turns = conversations.setdefault(str(conv_id), [])
                        if key not in {(t[0], t[1], t[2]) for t in turns}:
                            turns.append(
                                (row.get("_turn_idx", 0), role, content,
                                 row.get("language") or row.get("lang")))
                            n += 1
                            if raw_out is not None:
                                raw_out.write(json.dumps(rec, ensure_ascii=False) + "\n")
                                raw_n += 1
                        else:
                            n_dup += 1
                        conv_source[str(conv_id)] = src_repo
                    else:
                        t = _extract_text(row)
                        if isinstance(t, str) and t.strip():
                            # hash-based dedup: 20 bytes/row instead of full
                            # strings (the old seen_texts set OOM-thrashed
                            # the runner on v1-scale data -> timeout)
                            eh = _h(t)
                            if eh in seen_texts:
                                n_dup += 1
                                continue
                            seen_texts.add(eh)
                            nh = _h(normalize_text(t))
                            if nh in seen_norm:
                                n_norm_dup += 1
                                continue
                            seen_norm.add(nh)
                            # classify jobs emit GlotLID `label`; extract jobs use lang fields
                            raw_lang = row.get("lang") or row.get("language") or row.get("label")
                            split = normalize_lang(raw_lang, spec_lang)
                            flags = flag_text(t) if args.flag_content else empty_flags()
                            for fk, fv in flags.items():
                                if fv:
                                    flag_counter[fk] += 1
                            bump_stats(t)
                            pretrain_writer(split).write({
                                "id": make_id(src_repo, t),
                                "text": t, "source": src_repo, "lang": split,
                                "flags": flags, "dup_group": None})
                            split_counts[f"pretrain_{split}"] += 1
                            lang_counter[split] += 1
                            n += 1
                            if raw_out is not None:
                                raw_out.write(json.dumps(rec, ensure_ascii=False) + "\n")
                                raw_n += 1
                        elif row.get("label"):
                            # classify-only rows (no text): validation stats, not training rows
                            lang_counter[f"label:{row['label']}"] += 1
                    if args.max_rows and n >= args.max_rows:
                        break
        if raw_out is not None:
            raw_out.close()
            composition.append(f"- raw/{job_id}/train.jsonl: {raw_n:,} rows ({src_repo})")
        composition.append(f"- job {job_id}: {n:,} rows merged ({src_repo})")

    # ---- curated human contributions (source: humn_curated) ----
    n_curated = n_curated_bad = 0
    if args.curated:
        cpath = Path(args.curated)
        if not cpath.exists():
            log(f"[error] curated file not found: {cpath}", file=sys.stderr)
            return 1
        with open(cpath, encoding="utf-8") as fh:
            for i, line in enumerate(fh, 1):
                d = validate_curated_line(line, i)
                if d is None:
                    n_curated_bad += 1
                    continue
                cid = f"curated-{make_id(d['prompt'], d['response'])}"
                conversations.setdefault(cid, []).append((0, "user", d["prompt"], d["dialect"]))
                conversations[cid].append((1, "assistant", d["response"], d["dialect"]))
                conv_source[cid] = "humn_curated"
                n_curated += 1
        used_sources.add("humn_curated")
        log(f"[curated] accepted={n_curated} skipped={n_curated_bad} from {cpath.name}")

    # emit grouped chat conversations (sorted by turn index) into per-lang splits
    n_chat = 0
    for conv_id, turns in conversations.items():
        turns.sort(key=lambda t: t[0])
        msgs = [{"role": r, "content": c} for _, r, c, _ in turns if r in ("user", "assistant")]
        if len(msgs) >= 2:
            chat_lang = next((lg for _, _, _, lg in turns if lg), None)
            split = normalize_lang(chat_lang, None)
            full_text = "\n".join(m["content"] for m in msgs)
            flags = flag_text(full_text) if args.flag_content else empty_flags()
            for fk, fv in flags.items():
                if fv:
                    flag_counter[f"chat_{fk}"] += 1
            bump_stats(full_text)
            chat_writer(split).write({
                "id": make_id(conv_source[conv_id], conv_id),
                "conversation_id": conv_id, "messages": msgs,
                "source": conv_source[conv_id], "lang": split,
                "flags": flags})
            n_chat += 1
            split_counts[f"sft_chat_{split}"] += 1
            lang_counter[f"chat:{split}"] += 1
    # close all writers, collect per-split file lists
    split_files: dict[str, list[Path]] = {}
    for split, w in list(pretrain_writers.items()) + list(chat_writers.items()):
        kind = "pretrain" if split in pretrain_writers else "sft_chat"
        files = w.close()
        split_files[f"{kind}_{split}"] = files
    total_rows = sum(split_counts.values())
    avg_chars = _char_sum / _char_n if _char_n else 0
    med_chars = sorted(_len_reservoir)[len(_len_reservoir) // 2] if _len_reservoir else 0
    total_in = total_rows + n_dup + n_norm_dup
    log(f"\n[merged] {total_rows:,} canonical rows "
          f"(exact-dup removed: {n_dup:,}, normalized near-dup removed: {n_norm_dup:,})")
    for split in sorted(split_counts):
        log(f"  {split}: {split_counts[split]:,} rows")
    log(f"[quality] avg_len={avg_chars:.0f} chars, median_len~{med_chars}, "
          f"emoji_rows={_emoji_rows:,}, url_rows={_url_rows:,}")
    if flag_counter:
        log("[flags] " + ", ".join(f"{k}={v:,}" for k, v in flag_counter.most_common()))

    for split in sorted(split_counts):
        composition.append(f"- {split}/train-*.jsonl: {split_counts[split]:,} rows")
    if args.include_raw:
        composition.append("- raw/<job_id>/train.jsonl: per-job source dumps (provenance)")

    # stats file: machine-readable counters for finalize_release (sums across legs)
    stats = {"split_counts": dict(split_counts),
             "lang_counter": dict(lang_counter),
             "flag_counter": dict(flag_counter),
             "n_dup": n_dup, "n_norm_dup": n_norm_dup,
             "total_rows": total_rows,
             "used_sources": sorted(used_sources),
             "avg_chars": round(avg_chars, 1), "median_chars": med_chars,
             "emoji_rows": _emoji_rows, "url_rows": _url_rows}
    stats_path = None
    if args.save_stats:
        stats_path = Path(args.save_stats)
        stats_path.parent.mkdir(parents=True, exist_ok=True)
        stats_path.write_text(json.dumps(stats, ensure_ascii=False, indent=1), encoding="utf-8")
        log(f"[stats] {stats_path}")

    # dataset card — aggregate is ODC-By (required by ODC-By §4.2a for
    # derivative databases of ODC-By sources); per-source terms below.
    sources_txt = "\n".join(
        f"- {repo} — {lic} — {url}"
        for repo, (lic, url) in ATTRIBUTIONS.items() if repo in used_sources)
    unknown_src = sorted(used_sources - set(ATTRIBUTIONS))
    if unknown_src:
        log(f"  [warn] sources missing from ATTRIBUTIONS: {unknown_src}")
        sources_txt += "\n" + "\n".join(f"- {repo} — license: see source page" for repo in unknown_src)
    size_cat = "<1K" if total_rows < 1_000 else "1K<n<10K" if total_rows < 10_000 else \
               "10K<n<100K" if total_rows < 100_000 else "100K<n<1M" if total_rows < 1_000_000 else "1M<n<10M"
    langmix_txt = "\n".join(f"- {k}: {v:,}" for k, v in lang_counter.most_common(15)) or "- UNKNOWN"
    quality_txt = (
        f"- canonical rows: {total_rows:,}\n"
        f"- exact duplicates removed: {n_dup:,}\n"
        f"- normalized near-duplicates removed: {n_norm_dup:,}\n"
        f"- avg text length: {avg_chars:.0f} chars (median ~{med_chars})\n"
        f"- rows with emoji: {_emoji_rows:,} | rows with URLs: {_url_rows:,}\n"
        + ("\n".join(f"- flagged {k}: {v:,}" for k, v in flag_counter.most_common())
           if flag_counter else "- flags: none (flagging disabled)")
        + "\n- methods: exact SHA match → NFKC/lowercase/diacritic-stripped near-dup; "
          "lexicon heuristic flags v0 (transformer pass planned v1.1); "
          "MinHash-LSH near-dup planned v1.1"
    )
    card = CARD.format(version="v" + args.dataset_version.lstrip("v"),
                       size_cat=size_cat, composition="\n".join(composition),
                       sources=sources_txt, langmix=langmix_txt, quality=quality_txt)
    card_p = workdir / "final" / "README.md"
    card_p.write_text(card, encoding="utf-8")
    log(f"[card] {card_p}")

    if args.upload:
        if not token:
            log("[error] no HF token for upload", file=sys.stderr)
            return 1
        from worker_core import hf_upload_file
        # upload preserving relative paths, namespaced by --out-prefix for legs
        for rel in sorted((workdir / "final").rglob("*.jsonl")):
            rel_path = rel.relative_to(workdir / "final").as_posix()
            if rel.stat().st_size == 0:
                log(f"  [skip empty] {rel_path}")
                continue
            up_path = f"{UP_PREFIX}/{rel_path}" if UP_PREFIX else rel_path
            log(f"  [upload] {up_path} ...")
            hf_upload_file(args.out_repo, rel, up_path, token)
        if stats_path is not None and stats_path.exists():
            up_stats = f"{UP_PREFIX}/stats.json" if UP_PREFIX else "stats.json"
            hf_upload_file(args.out_repo, stats_path, up_stats, token)
        if not UP_PREFIX:
            # legs never own the card; only the final release writes it
            hf_upload_file(args.out_repo, card_p, "README.md", token)
        log(f"\n[UPLOADED] https://huggingface.co/datasets/{args.out_repo}"
            + (f" under {UP_PREFIX}/" if UP_PREFIX else ""))
    else:
        log(f"\n[dev] files ready in {workdir / 'final'} (no upload; add --upload --token <hf_write_token>)")
    return 0


