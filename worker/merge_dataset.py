class ShardWriter:
    """JSONL writer that rolls over to train-00001, train-00002... at max_bytes.

    Keeps every file viewer-friendly (no multi-GB single files).
    All shards share one schema because the caller writes uniform rows.
    """

    def __init__(self, directory: Path, max_bytes: int = 400 * 1024 * 1024):
        self.directory = directory
        self.directory.mkdir(parents=True, exist_ok=True)
        self.max_bytes = max_bytes
        self.index = 0
        self.rows = 0
        self.files: list[Path] = []
        self._fh = None
        self._bytes = 0
        self._open_next()

    def _open_next(self) -> None:
        if self._fh:
            self._fh.close()
        path = self.directory / f"train-{self.index:05d}.jsonl"
        self._fh = open(path, "w", encoding="utf-8")
        self.files.append(path)
        self._bytes = 0
        self.index += 1

    def write(self, obj: dict) -> None:
        line = json.dumps(obj, ensure_ascii=False) + "\n"
        data = line.encode("utf-8")
        if self._bytes + len(data) > self.max_bytes and self._bytes > 0:
            self._open_next()
        self._fh.write(line)
        self._bytes += len(data)
        self.rows += 1

    def close(self) -> list[Path]:
        if self._fh:
            self._fh.close()
            self._fh = None
        # drop a trailing empty shard if the last rollover wrote nothing
        if self.files and self.files[-1].stat().st_size == 0 and len(self.files) > 1:
            self.files[-1].unlink()
            self.files.pop()
        return self.files


LANG_MAP = {
    # GlotLID labels
    "arz_Arab": "ar_eg", "arb_Arab": "ar_msa", "apc_Arab": "ar_levant",
    "ars_Arab": "ar_gulf", "ary_Arab": "ar_maghrebi", "aeb_Arab": "ar_maghrebi",
    "acm_Arab": "ar_gulf",  # Mesopotamian/Iraqi approx — closest available bucket
    # short codes + generic labels
    "arz": "ar_eg", "arb": "ar_msa", "apc": "ar_levant", "ars": "ar_gulf",
    "ary": "ar_maghrebi", "aeb": "ar_maghrebi", "acm": "ar_gulf",
    "ar": "ar_msa", "Arabic": "ar_msa", "ara": "ar_msa",
    "en": "en", "eng": "en", "eng_Latn": "en", "English": "en",
}


def normalize_lang(raw, spec_default: str | None) -> str:
    """Map any language label to a v1 split name.

    Unknown labels quarantine to 'mixed' — never silently bucketed as MSA.
    """
    if raw is not None and str(raw) in LANG_MAP:
        return LANG_MAP[str(raw)]
    if spec_default:
        return spec_default
    return "mixed"


def make_id(*parts: str) -> str:
    import hashlib

    return hashlib.sha1("|".join(parts).encode("utf-8")).hexdigest()[:16]


def empty_flags() -> dict:
    return {"political": False, "toxic": False, "spam": False, "low_info": False}


def _extract_text(row: dict) -> str | None:
    """Pull usable text from any known schema. Returns None if none found."""
    for key in ("text", "selftext", "tweet", "content", "body", "prompt"):
        v = row.get(key)
        if isinstance(v, str) and v.strip():
            return v
    # Aya-style: inputs + targets
    parts = []
    for key in ("inputs", "targets", "completion", "response"):
        v = row.get(key)
        if isinstance(v, dict):
            v = v.get("text") or json.dumps(v, ensure_ascii=False)
        if isinstance(v, str) and v.strip():
            parts.append(v)
    if parts:
        return "\n".join(parts)
    return None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--jobs-dir", required=True)
    ap.add_argument("--workdir", required=True)
    ap.add_argument("--out-repo", required=True,
                    help="e.g. yourname/humn-social-register-v0.2, or 'auto'")
    ap.add_argument("--dataset-version", default="v0.2",
                    help="used for auto repo naming + dataset card title")
    ap.add_argument("--token", default=None, help="HF write token (or env HUMN_OUT_TOKEN)")
    ap.add_argument("--max-rows", type=int, default=None)
    ap.add_argument("--download", action="store_true",
                    help="download finished chunks from the HF checkpoint repo")
    ap.add_argument("--upload", action="store_true", help="actually upload (default: dev, local only)")
    ap.add_argument("--exclude-sources", default="",
                    help="comma-separated source repos to EXCLUDE (e.g. lmsys/lmsys-chat-1m for public releases)")
    ap.add_argument("--split-by-lang", action=argparse.BooleanOptionalAction, default=True,
                    help="write per-language pretrain_<lang>/ dirs instead of one pretrain/ dir")
    ap.add_argument("--include-raw", action="store_true", default=False,
                    help="also publish raw/<job>/ provenance dumps (default: slim release without them)")
    args = ap.parse_args()

    token = args.token or __import__("os").environ.get("HUMN_OUT_TOKEN") or __import__("os").environ.get("HF_TOKEN_RW")
    if args.out_repo == "auto":
        if not token:
            print("[error] --out-repo auto needs a token to resolve your username", file=sys.stderr)
            return 1
        from worker_core import hf_whoami
        user = hf_whoami(token)
        ver = args.dataset_version.lstrip("v")
        args.out_repo = f"{user}/humn-social-register-v{ver}"
        print(f"[auto] output repo: {args.out_repo}")
    workdir = Path(args.workdir)
    workdir.mkdir(parents=True, exist_ok=True)

    jobs_dir = Path(args.jobs_dir)
    excluded = {s.strip() for s in args.exclude_sources.split(",") if s.strip()}
    if excluded:
        print(f"[exclude] dropping sources from public release: {sorted(excluded)}")
    composition: list[str] = []
    seen_texts: set[str] = set()
    n_dup = 0
    # v1 layout: per-language pretrain_<lang>/ + per-language sft_chat_<lang>/,
    # each a separate HF config with ONE uniform canonical schema.
    # ShardWriter keeps every file <= ~400MB (viewer-friendly).
    final_dir = workdir / "final"
    final_dir.mkdir(parents=True, exist_ok=True)
    pretrain_writers: dict[str, ShardWriter] = {}
    chat_writers: dict[str, ShardWriter] = {}
    split_counts: Counter = Counter()
    conversations: dict[str, list] = {}   # conversation_id -> turns
    conv_source: dict[str, str] = {}
    lang_counter: Counter = Counter()     # language mix stats
    used_sources: set[str] = set()

    def pretrain_writer(split: str) -> ShardWriter:
        if split not in pretrain_writers:
            pretrain_writers[split] = ShardWriter(final_dir / f"pretrain_{split}")
        return pretrain_writers[split]

    def chat_writer(split: str) -> ShardWriter:
        if split not in chat_writers:
            chat_writers[split] = ShardWriter(final_dir / f"sft_chat_{split}")
        return chat_writers[split]

    for spec_file in sorted(jobs_dir.glob("*.yaml")):
        with open(spec_file, encoding="utf-8") as f:
            spec = yaml.safe_load(f) or {}
        if not spec:
            continue
        job_id = spec.get("job_id", spec_file.stem)
        manifest_p = workdir / job_id / "manifest.json"

        if not manifest_p.exists() and args.download:
            # pull manifest + done chunks from the (resolved) checkpoint repo
            if not token:
                print(f"[skip] {job_id}: --download needs a token", file=sys.stderr)
                continue
            from worker_core import resolve_repo
            ckpt_repo = resolve_repo(spec["checkpoint"]["repo"], token)
            try:
                from huggingface_hub import hf_hub_download  # type: ignore
                mpath = hf_hub_download(repo_id=ckpt_repo, filename="manifest.json",
                                        repo_type="dataset", token=token)
                manifest = json.loads(Path(mpath).read_text(encoding="utf-8"))
                manifest_p.parent.mkdir(parents=True, exist_ok=True)
                manifest_p.write_text(json.dumps(manifest, ensure_ascii=False), encoding="utf-8")
                for c in manifest["chunks"]:
                    if c["status"] == "done":
                        cp = hf_hub_download(repo_id=ckpt_repo,
                                             filename=f"{job_id}/{c['chunk_id']}.jsonl",
                                             repo_type="dataset", token=token)
                        dst = workdir / job_id / f"{c['chunk_id']}.jsonl"
                        dst.parent.mkdir(parents=True, exist_ok=True)
                        if not dst.exists():
                            import shutil
                            shutil.copy(cp, dst)
                print(f"[download] {job_id}: chunks fetched from {ckpt_repo}")
            except Exception as e:  # noqa: BLE001
                print(f"[skip] {job_id}: no remote checkpoint ({type(e).__name__}: {str(e)[:150]})")
                continue

        if not manifest_p.exists():
            print(f"[skip] {job_id}: no manifest (job not run)")
            continue
        manifest = json.loads(manifest_p.read_text(encoding="utf-8"))
        done = [c for c in manifest["chunks"] if c["status"] == "done"]
        src_repo = spec["data_source"]["repo"]
        if src_repo in excluded:
            print(f"[excluded] {job_id} ({src_repo}) — purged from this release")
            continue
        used_sources.add(src_repo)
        spec_lang = (spec.get("metadata") or {}).get("lang")
        print(f"[merge] {job_id}: {len(done)} chunks from {src_repo}"
              + (f" (spec lang: {spec_lang})" if spec_lang else ""))
        raw_out = None
        raw_n = 0
        if args.include_raw:
            raw_job_dir = final_dir / "raw" / job_id
            raw_job_dir.mkdir(parents=True, exist_ok=True)
            raw_out = open(raw_job_dir / "train.jsonl", "w", encoding="utf-8")
        n = 0
        for c in done:
            chunk_p = workdir / job_id / f"{c['chunk_id']}.jsonl"
            if not chunk_p.exists():
                print(f"  [warn] chunk file missing: {chunk_p.name}")
                continue
            with open(chunk_p, encoding="utf-8") as fh:
                for line in fh:
                    try:
                        rec = json.loads(line)
                    except json.JSONDecodeError:
                        n_dup += 1
                        continue
                    text = json.dumps(rec, sort_keys=True)
                    if text in seen_texts:
                        n_dup += 1
                        continue
                    seen_texts.add(text)
                    rec["source"] = src_repo
                    if raw_out is not None:
                        raw_out.write(json.dumps(rec, ensure_ascii=False) + "\n")
                        raw_n += 1
                    n += 1
                    # ---- canonical routing ----
                    row = rec.get("row", {})
                    if not isinstance(row, dict):
                        row = {"value": row}
                    role = row.get("role")
                    content = row.get("content")
                    conv_id = row.get("parent_conversation_id") or row.get("parent_id")
                    if isinstance(role, str) and isinstance(content, str) and conv_id:
                        conversations.setdefault(str(conv_id), []).append(
                            (row.get("_turn_idx", 0), role, content,
                             row.get("language") or row.get("lang")))
                        conv_source[str(conv_id)] = src_repo
                    else:
                        t = _extract_text(row)
                        if isinstance(t, str) and t.strip():
                            # classify jobs emit GlotLID `label`; extract jobs use lang fields
                            raw_lang = row.get("lang") or row.get("language") or row.get("label")
                            split = normalize_lang(raw_lang, spec_lang)
                            pretrain_writer(split).write({
                                "id": make_id(src_repo, t),
                                "text": t, "source": src_repo, "lang": split,
                                "flags": empty_flags(), "dup_group": None})
                            split_counts[f"pretrain_{split}"] += 1
                            lang_counter[split] += 1
                        elif row.get("label"):
                            # classify-only rows (no text): validation stats, not training rows
                            lang_counter[f"label:{row['label']}"] += 1
                    if args.max_rows and n >= args.max_rows:
                        break
        if raw_out is not None:
            raw_out.close()
            composition.append(f"- raw/{job_id}/train.jsonl: {raw_n:,} rows ({src_repo})")
        composition.append(f"- job {job_id}: {n:,} rows merged ({src_repo})")

    # emit grouped chat conversations (sorted by turn index) into per-lang splits
    n_chat = 0
    for conv_id, turns in conversations.items():
        turns.sort(key=lambda t: t[0])
        msgs = [{"role": r, "content": c} for _, r, c, _ in turns if r in ("user", "assistant")]
        if len(msgs) >= 2:
            chat_lang = next((lg for _, _, _, lg in turns if lg), None)
            split = normalize_lang(chat_lang, None)
            chat_writer(split).write({
                "id": make_id(conv_source[conv_id], conv_id),
                "conversation_id": conv_id, "messages": msgs,
                "source": conv_source[conv_id], "lang": split,
                "flags": empty_flags()})
            n_chat += 1
            split_counts[f"sft_chat_{split}"] += 1
            lang_counter[f"chat:{split}"] += 1
    # close all writers, collect per-split file lists
    split_files: dict[str, list[Path]] = {}
    for split, w in list(pretrain_writers.items()) + list(chat_writers.items()):
        prefix = "pretrain" if split in pretrain_writers else "sft_chat"
        files = w.close()
        split_files[f"{prefix}_{split}"] = files
    total_rows = sum(split_counts.values())
    print(f"\n[merged] {total_rows:,} canonical rows, {n_dup:,} duplicates removed")
    for split in sorted(split_counts):
        print(f"  {split}: {split_counts[split]:,} rows")

    for split in sorted(split_counts):
        composition.append(f"- {split}/train-*.jsonl: {split_counts[split]:,} rows")
    if args.include_raw:
        composition.append("- raw/<job_id>/train.jsonl: per-job source dumps (provenance)")

    # dataset card — aggregate is ODC-By (required by ODC-By §4.2a for
    # derivative databases of ODC-By sources); per-source terms below.
    sources_txt = "\n".join(
        f"- {repo} — {lic} — {url}"
        for repo, (lic, url) in ATTRIBUTIONS.items() if repo in used_sources)
    unknown_src = sorted(used_sources - set(ATTRIBUTIONS))
    if unknown_src:
        print(f"  [warn] sources missing from ATTRIBUTIONS: {unknown_src}")
        sources_txt += "\n" + "\n".join(f"- {repo} — license: see source page" for repo in unknown_src)
    size_cat = "<1K" if total_rows < 1_000 else "1K<n<10K" if total_rows < 10_000 else \
               "10K<n<100K" if total_rows < 100_000 else "100K<n<1M" if total_rows < 1_000_000 else "1M<n<10M"
    langmix_txt = "\n".join(f"- {k}: {v:,}" for k, v in lang_counter.most_common(15)) or "- UNKNOWN"
    card = CARD.format(version="v" + args.dataset_version.lstrip("v"),
                       size_cat=size_cat, composition="\n".join(composition),
                       sources=sources_txt, langmix=langmix_txt)
    card_p = workdir / "final" / "README.md"
    card_p.write_text(card, encoding="utf-8")
    print(f"[card] {card_p}")

    if args.upload:
        if not token:
            print("[error] no HF token for upload", file=sys.stderr)
            return 1
        from worker_core import hf_upload_file
        # upload preserving relative paths: pretrain/, sft_chat/, raw/<job>/, README
        for rel in sorted((workdir / "final").rglob("*.jsonl")):
            rel_path = rel.relative_to(workdir / "final").as_posix()
            if rel.stat().st_size == 0:
                print(f"  [skip empty] {rel_path}")
                continue
            hf_upload_file(args.out_repo, rel, rel_path, token)
        hf_upload_file(args.out_repo, card_p, "README.md", token)
        print(f"\n[UPLOADED] https://huggingface.co/datasets/{args.out_repo}")
    else:
        print(f"\n[dev] files ready in {workdir / 'final'} (no upload; add --upload --token <hf_write_token>)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
